/**
 * New Bytes (api.nb.com.ar) desde el servidor. Sirve al proxy del panel y a la sincronización automática.
 * Credenciales en las variables de entorno NB_API_USER y NB_API_PASSWORD (la cuenta de nb.com.ar con
 * "Integraciones y API" habilitado); nunca salen en las respuestas ni en los registros.
 *
 * El catálogo es una sola consulta (GET /v1/ con el token). Cada producto trae, entre otros:
 * id, sku, title, amountStock, price {value (USD sin IVA), iva, finalPrice}, cotizacion,
 * category / categoryDescriptionUser, mainImage / mainImageExp y peso y medidas promedio
 * (weightAverage en gramos; widthAverage, lengthAverage y highAverage en milímetros).
 */

const NB_API = "https://api.nb.com.ar/v1";
const ESPERA_LOGIN_MS = 15_000;
const ESPERA_CATALOGO_MS = 40_000;
const VIGENCIA_DEL_TOKEN_MS = 45 * 60_000;

export interface PrecioNewBytes {
  value?: number | string;
  iva?: number | string;
  finalPrice?: number | string;
  [clave: string]: unknown;
}

export interface ProductoNewBytes {
  id: number | string;
  sku?: string;
  title?: string;
  amountStock?: number | string;
  price?: PrecioNewBytes;
  cotizacion?: number | string;
  category?: string;
  categoryDescriptionUser?: string;
  mainImage?: string;
  mainImageExp?: string;
  weightAverage?: number | string;
  widthAverage?: number | string;
  lengthAverage?: number | string;
  highAverage?: number | string;
  [clave: string]: unknown;
}

export interface CamposDeNewBytes {
  cost_price: number;
  source_cost_price: number;
  source_currency: "USD";
  source_exchange_rate: number | null;
  stock_available: number;
  active: boolean;
  lead_time_days: number;
}

let tokenGuardado: { token: string; vence: number } | null = null;

export function hayCredencialesDeNewBytes(): boolean {
  return Boolean(process.env.NB_API_USER?.trim() && process.env.NB_API_PASSWORD?.trim());
}

const numero = (valor: unknown): number => {
  if (typeof valor === "number") return Number.isFinite(valor) ? valor : 0;
  const n = Number(String(valor ?? "").trim().replace(",", "."));
  return Number.isFinite(n) ? n : 0;
};

async function pedirToken(): Promise<string> {
  if (tokenGuardado && tokenGuardado.vence > Date.now()) return tokenGuardado.token;
  if (!hayCredencialesDeNewBytes()) throw new Error("Faltan NB_API_USER y NB_API_PASSWORD en Vercel.");
  const respuesta = await fetch(`${NB_API}/auth/login`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ user: process.env.NB_API_USER?.trim(), password: process.env.NB_API_PASSWORD?.trim(), mode: "api" }),
    signal: AbortSignal.timeout(ESPERA_LOGIN_MS),
  });
  if (!respuesta.ok) throw new Error(`New Bytes no aceptó el ingreso (${respuesta.status}). Revisá el usuario y la contraseña.`);
  const json = (await respuesta.json().catch(() => ({}))) as { token?: unknown };
  if (typeof json.token !== "string" || !json.token) throw new Error("New Bytes no devolvió el token de ingreso.");
  tokenGuardado = { token: json.token, vence: Date.now() + VIGENCIA_DEL_TOKEN_MS };
  return json.token;
}

export function productosDe(payload: unknown): ProductoNewBytes[] {
  if (Array.isArray(payload)) return payload as ProductoNewBytes[];
  if (payload && typeof payload === "object") {
    for (const clave of ["data", "products", "productos", "items", "result"]) {
      const valor = (payload as Record<string, unknown>)[clave];
      if (Array.isArray(valor)) return valor as ProductoNewBytes[];
    }
  }
  return [];
}

async function conToken(ruta: string, espera: number): Promise<Response> {
  const pedir = async () =>
    fetch(`${NB_API}${ruta}`, {
      headers: { Authorization: `Bearer ${await pedirToken()}`, "Content-Type": "application/json" },
      signal: AbortSignal.timeout(espera),
    });
  let respuesta = await pedir();
  if (respuesta.status === 401) {
    tokenGuardado = null;
    respuesta = await pedir();
  }
  return respuesta;
}

/** La respuesta cruda del catálogo, para reenviarla al panel sin esperar a leerla entera. */
export async function respuestaDelCatalogo(): Promise<Response> {
  const respuesta = await conToken("/", ESPERA_CATALOGO_MS);
  if (!respuesta.ok) throw new Error(`New Bytes respondió ${respuesta.status} al pedir el catálogo.`);
  return respuesta;
}

/** El catálogo completo de New Bytes. */
export async function catalogoDeNewBytes(): Promise<ProductoNewBytes[]> {
  return productosDe(await (await respuestaDelCatalogo()).json());
}

/** La descripción que New Bytes genera para un producto, o null. */
export async function descripcionDeNewBytes(id: string): Promise<string | null> {
  const respuesta = await conToken(`/autoGeneratedDescription/${encodeURIComponent(id)}`, ESPERA_LOGIN_MS);
  if (!respuesta.ok) return null;
  const json = (await respuesta.json().catch(() => null)) as Record<string, unknown> | string | null;
  if (typeof json === "string") return json.trim() || null;
  const texto = json?.description ?? json?.descripcion ?? json?.text ?? (json?.data as Record<string, unknown> | undefined)?.description;
  return typeof texto === "string" && texto.trim() ? texto.trim() : null;
}

/**
 * Todas las descripciones que New Bytes genera para sus productos, en una sola consulta
 * (GET /autoGeneratedDescriptions → [{codigo, description}], donde codigo es el id del producto).
 */
export async function descripcionesDeNewBytes(): Promise<Map<string, string>> {
  const respuesta = await conToken("/autoGeneratedDescriptions", ESPERA_CATALOGO_MS);
  if (!respuesta.ok) throw new Error(`New Bytes respondió ${respuesta.status} al pedir las descripciones.`);
  const json = (await respuesta.json().catch(() => null)) as unknown;
  const lista = Array.isArray(json)
    ? json
    : json && typeof json === "object"
      ? ((["data", "descriptions", "items", "result"].map((k) => (json as Record<string, unknown>)[k]).find(Array.isArray) as unknown[] | undefined) ?? [])
      : [];
  const mapa = new Map<string, string>();
  for (const item of lista as Array<Record<string, unknown>>) {
    const codigo = item?.codigo ?? item?.id ?? item?.productId;
    const texto = item?.description ?? item?.descripcion;
    if ((typeof codigo === "string" || typeof codigo === "number") && typeof texto === "string" && texto.trim()) {
      mapa.set(String(codigo), texto);
    }
  }
  return mapa;
}

const ENTIDADES: Record<string, string> = {
  "&nbsp;": " ", "&amp;": "&", "&lt;": "<", "&gt;": ">", "&quot;": '"', "&#39;": "'", "&aacute;": "á", "&eacute;": "é", "&iacute;": "í",
  "&oacute;": "ó", "&uacute;": "ú", "&ntilde;": "ñ", "&Aacute;": "Á", "&Eacute;": "É", "&Iacute;": "Í", "&Oacute;": "Ó", "&Uacute;": "Ú",
  "&Ntilde;": "Ñ", "&uuml;": "ü", "&deg;": "°", "&reg;": "®", "&trade;": "™", "&iquest;": "¿", "&iexcl;": "",
};

/**
 * La descripción de New Bytes como texto de la ficha: sin HTML, un párrafo por línea, sin signos de
 * exclamación ni emojis (reglas de voz de Teqo).
 */
export function textoDeDescripcion(crudo: string): string {
  let t = crudo
    .replace(/<\s*br\s*\/?>/gi, "\n")
    .replace(/<\s*li[^>]*>/gi, "\n- ")
    .replace(/<\/\s*(p|div|li|h\d|ul|ol|tr)\s*>/gi, "\n")
    .replace(/<[^>]+>/g, " ");
  t = t.replace(/&[a-zA-Z]+;|&#\d+;/g, (e) => ENTIDADES[e] ?? (e.startsWith("&#") ? String.fromCharCode(Number(e.slice(2, -1))) : " "));
  t = t
    .replace(/[¡!]+/g, (signos) => (signos.includes("!") ? "." : ""))
    .replace(/\.\.+/g, ".")
    .replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}]/gu, "");
  const lineas = t
    .split("\n")
    .map((l) => l.replace(/[ \t]+/g, " ").trim())
    .filter((l) => l && l !== "-");
  return lineas.join("\n").slice(0, 6000).trim();
}

/** Costo en dólares sin IVA y stock, para product_suppliers. */
export function camposDeNewBytes(producto: ProductoNewBytes): CamposDeNewBytes {
  const costo = numero(producto.price?.value);
  const cotizacion = numero(producto.cotizacion) || null;
  const stock = Math.max(0, Math.round(numero(producto.amountStock)));
  return {
    cost_price: Number(costo.toFixed(4)),
    source_cost_price: costo,
    source_currency: "USD",
    source_exchange_rate: cotizacion,
    stock_available: stock,
    active: stock > 0 || costo > 0,
    lead_time_days: 0,
  };
}
