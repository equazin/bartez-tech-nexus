-- =============================================================================
-- Teqo · Tablas base heredadas de Bartez
-- En Bartez, products, orders y categories se crearon a mano antes del historial
-- de migraciones (las migraciones siguientes solo les agregan columnas). En un
-- proyecto nuevo hay que crearlas primero, con las columnas que ese historial y
-- el código dan por existentes. Todo es idempotente.
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS categories (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS products (
  id                  serial PRIMARY KEY,
  name                text NOT NULL,
  description         text,
  image               text,
  cost_price          numeric(14,4),
  category            text,
  stock               integer NOT NULL DEFAULT 0,
  sku                 text,
  supplier_id         integer,
  supplier_name       text,
  supplier_multiplier numeric(8,4) NOT NULL DEFAULT 1,
  stock_min           integer NOT NULL DEFAULT 0,
  external_id         text,
  active              boolean NOT NULL DEFAULT true,
  featured            boolean NOT NULL DEFAULT false,
  specs               jsonb,
  tags                text[],
  unit_price          numeric(14,4),
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_products_active   ON products(active);
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category);
CREATE INDEX IF NOT EXISTS idx_products_sku      ON products(sku);

CREATE TABLE IF NOT EXISTS orders (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id   uuid,
  seller_id   uuid,
  products    jsonb NOT NULL DEFAULT '[]'::jsonb,
  total       numeric(14,2) NOT NULL DEFAULT 0,
  status      text NOT NULL DEFAULT 'pending',
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_orders_client ON orders(client_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);

-- Fotos de productos y de bundles: públicas para leer, el panel sube con sesión.
INSERT INTO storage.buckets (id, name, public) VALUES ('products', 'products', true) ON CONFLICT (id) DO NOTHING;
INSERT INTO storage.buckets (id, name, public) VALUES ('bundles', 'bundles', true) ON CONFLICT (id) DO NOTHING;

DROP POLICY IF EXISTS "products_bucket_leer" ON storage.objects;
CREATE POLICY "products_bucket_leer" ON storage.objects FOR SELECT TO anon, authenticated USING (bucket_id IN ('products', 'bundles'));
